#!/usr/bin/env python3
"""Generates hann4096.hex and src/pitch/NoteRom.v / StringRom.v  (run from GuitarTuner/)."""
import numpy as np
FS = 50e6/1024/16          # decimated sample rate (CIC /16)
N = 4096
UNIT = FS/N/256            # frequency unit used inside the FPGA: 1/256 of an FFT bin (Hz)
print(f"FS_d={FS:.4f} Hz  bin={FS/N:.6f} Hz  unit={UNIT:.9f} Hz")

# --- Hann window (periodic), 16-bit unsigned
n = np.arange(N)
w = np.round(0.5*(1-np.cos(2*np.pi*n/N))*65535).astype(int)
with open("Verilog/hann4096.hex", "w") as f:
    for v in w: f.write(f"{v:04X}\n")

def fm(m): return 440.0*2**((m-69)/12)
def rom(name, midis, comment):
    L = []
    L.append(f"// AUTO-GENERATED by tools/gen_tables.py -- {comment}")
    L.append(f"// freq/bound are in units of {UNIT:.9f} Hz (1/256 of an FFT bin).")
    L.append(f"module {name}(input [5:0] idx, output reg [17:0] freq, output reg [17:0] bound, output reg [6:0] midi);")
    L.append("\talways @* begin\n\t\tcase (idx)")
    for i, m in enumerate(midis):
        fr = round(fm(m)/UNIT)
        bd = round(np.sqrt(fm(m)*fm(midis[i+1]))/UNIT) if i < len(midis)-1 else 262143   # geometric midpoint to the next entry
        L.append(f"\t\t\t6'd{i}: begin freq = 18'd{fr}; bound = 18'd{bd}; midi = 7'd{m}; end  // {fm(m):.3f} Hz")
    L.append(f"\t\t\tdefault: begin freq = 18'd{round(fm(midis[-1])/UNIT)}; bound = 18'd262143; midi = 7'd{midis[-1]}; end")
    L.append("\t\tendcase\n\tend\nendmodule")
    open(f"Verilog/src/pitch/{name}.v", "w").write("\n".join(L)+"\n")

rom("NoteRom", list(range(36, 73)), "chromatic notes C2..C5 (MIDI 36..72), bound = geometric midpoint to next note")
rom("StringRom", [40, 45, 50, 55, 59, 64], "standard guitar strings E2 A2 D3 G3 B3 E4")
